CREATE TABLE usuarios (
 id UUID PRIMARY KEY, nombre VARCHAR(120) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE,
 telefono VARCHAR(25) NOT NULL, password_hash VARCHAR(100) NOT NULL,
 rol VARCHAR(20) NOT NULL DEFAULT 'CLIENTE' CHECK (rol IN ('CLIENTE','ADMINISTRADOR','CAJA','COCINA','DELIVERY')),
 activo BOOLEAN NOT NULL DEFAULT TRUE, version_sesion BIGINT NOT NULL DEFAULT 0,
 cuenta TEXT NOT NULL DEFAULT '{}', creado TIMESTAMP WITH TIME ZONE NOT NULL,
 CONSTRAINT email_normalizado CHECK (email = LOWER(TRIM(email)))
);
CREATE TABLE recuperaciones (
 id UUID PRIMARY KEY, usuario_id UUID NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
 token_hash VARCHAR(64) NOT NULL UNIQUE, vence TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX recuperaciones_usuario ON recuperaciones(usuario_id);
